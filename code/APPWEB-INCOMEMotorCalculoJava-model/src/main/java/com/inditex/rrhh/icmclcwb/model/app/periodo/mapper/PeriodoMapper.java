package com.inditex.rrhh.icmclcwb.model.app.periodo.mapper;

import java.time.LocalDate;
import java.time.LocalDateTime;
import java.time.LocalTime;
import java.time.OffsetDateTime;
import java.time.ZoneOffset;
import java.util.List;

import com.inditex.rrhh.icmclcwb.api.meta4.icmwscalcincome.periodos.dto.PeriodosResultItemDto;
import com.inditex.rrhh.icmclcwb.dto.PeriodoDTO;
import com.inditex.rrhh.icmclcwb.rest.client.dto.PeriodoResponseDTO;

import org.mapstruct.InheritInverseConfiguration;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;

@Mapper
public abstract class PeriodoMapper {

  @Mapping(target = "id", source = "src.idPeriodo")
  @Mapping(target = "fechaInicioPeriodo", source = "src.fechaInicio")
  @Mapping(target = "fechaFinPeriodo", source = "src.fechaFin")
  public abstract PeriodoDTO periodoResultItemDtoToPeriodoDto(PeriodosResultItemDto src);

  public abstract List<PeriodoDTO> periodoResultItemDtoToPeriodoDto(List<PeriodosResultItemDto> src);

  @Mapping(target = "id", source = "src.idPeriodo")
  @Mapping(target = "fechaInicioPeriodo", source = "src.fechaInicio")
  @Mapping(target = "fechaFinPeriodo", source = "src.fechaFin")
  public abstract PeriodoDTO periodoResponseDtoToPeriodoDto(PeriodoResponseDTO src);

  @InheritInverseConfiguration
  @Mapping(target = "m4AutoGeneratedRecordID", ignore = true)
  @Mapping(target = "m4AutoGeneratedToDelete", ignore = true)
  @Mapping(target = "activo", ignore = true)
  @Mapping(target = "abierto", ignore = true)
  @Mapping(target = "borrado", ignore = true)
  @Mapping(target = "modificado", ignore = true)
  @Mapping(target = "nuevo", ignore = true)
  @Mapping(target = "idOrigen", ignore = true)
  @Mapping(target = "nombrePeriodo", ignore = true)
  public abstract PeriodosResultItemDto periodoDtoToPeriodoResultItemDto(PeriodoDTO src);

  public abstract List<PeriodosResultItemDto> periodoDtoToPeriodoResultItemDto(List<PeriodoDTO> src);

  OffsetDateTime map(final LocalDateTime value) {
    return value != null ? value.atOffset(ZoneOffset.UTC) : null;
  }

  LocalDateTime map(final OffsetDateTime value) {
    return value != null ? value.toLocalDateTime() : null;
  }

  OffsetDateTime mapLocalDate(final LocalDate value) {
    return value != null ? value.atTime(LocalTime.MIDNIGHT).atOffset(ZoneOffset.UTC) : null;
  }

  LocalDate mapLocalDate(final OffsetDateTime value) {
    return value.toLocalDate();
  }
}
