package com.inditex.rrhh.icmclcwb.model.meta4.icmwscalcincome.service;

import java.io.Serializable;
import java.util.List;
import java.util.function.Function;

import com.inditex.rrhh.icmclcwb.api.meta4.dto.PageableListDto;

import lombok.extern.slf4j.Slf4j;
import org.assertj.core.api.recursive.comparison.ComparisonDifference;
import org.assertj.core.api.recursive.comparison.RecursiveComparisonConfiguration;
import org.assertj.core.api.recursive.comparison.RecursiveComparisonDifferenceCalculator;
import org.springframework.stereotype.Component;

/**
 * Utility to compare the responses produced by the legacy SOAP implementation and the new REST implementation for the same operation, and
 * log any differences in a readable way.
 *
 * <p>Both responses are expected to be of the same type. Auto-generated SOAP-only bookkeeping fields ({@code m4AutoGeneratedRecordID},
 * {@code m4AutoGeneratedToDelete}) and collection ordering are ignored.
 *
 * <p>This component does not handle async execution; callers (e.g. {@link com.inditex.rrhh.icmclcwb.model.meta4.icmwscalcincome.util
 * .MigrationDispatcher}) are responsible for invoking it on the appropriate thread.
 */
@Component
@Slf4j
public class IncomeResponseComparator {

  private static final String[] IGNORED_FIELD_REGEXES = {
      ".*m4AutoGeneratedRecordID", ".*m4AutoGeneratedToDelete"
  };

  private static final RecursiveComparisonConfiguration COMPARISON_CONFIG = RecursiveComparisonConfiguration.builder()
      .withIgnoreCollectionOrder(true)
      .withIgnoredFieldsMatchingRegexes(IGNORED_FIELD_REGEXES)
      .build();

  private final RecursiveComparisonDifferenceCalculator calculator = new RecursiveComparisonDifferenceCalculator();

  /**
   * Compares the SOAP and REST responses for {@code operationName} and logs every difference found. Both responses must be of the same
   * type. Differences are logged at WARN level; matches are logged at DEBUG.
   */
  @SuppressWarnings({"unchecked", "rawtypes"})
  public <T, R> void compareAndLogDiffs(String operationName, T soapResponse, T restResponse, R request) {
    if (soapResponse instanceof PageableListDto<?> && restResponse instanceof PageableListDto<?>) {
      comparePageableListDto(operationName, (PageableListDto) soapResponse, (PageableListDto) restResponse, request);
      return;
    }
    if (soapResponse instanceof List<?> && restResponse instanceof List<?>) {
      compareLists(operationName, (List) soapResponse, (List) restResponse, request);
      return;
    }
    try {
      var diffs = calculator.determineDifferences(restResponse, soapResponse, COMPARISON_CONFIG);
      if (diffs.isEmpty()) {
        log.debug("Shadow REST and SOAP responses match for {}", operationName);
        return;
      }
      var sb = new StringBuilder();
      sb.append("Shadow REST and SOAP responses differ for ").append(operationName)
          .append(" (").append(diffs.size()).append(" diffs):");
      appendDiffsTabular(sb, diffs, diff -> String.join(".", diff.getDecomposedPath()));
      sb.append("\n  - Request body used: ").append(request);
      log.warn(sb.toString());
    } catch (Exception ex) {
      log.error("Error comparing SOAP and REST responses for {}.\nSOAP:\n\t{}\nREST:\n\t{}",
          operationName, soapResponse, restResponse, ex);
    }
  }

  /**
   * Compares the SOAP and REST responses for {@code operationName} when both are {@link PageableListDto}. The SOAP response may be
   * paginated; the REST response never is. The {@code page} field is ignored. The check is a subset check: every element of
   * {@code soapResponse.data} must be present (according to the recursive comparison config) in {@code restResponse.data}. For each SOAP
   * item that has no exact match, the closest REST item (the one with the fewest field-level diffs) is selected and each differing field is
   * logged individually with a {@code data[i].<path>} prefix.
   */
  public <T extends Serializable, R> void comparePageableListDto(String operationName, PageableListDto<T> soapResponse,
      PageableListDto<T> restResponse, R request) {
    try {
      if (checkResponses(operationName, soapResponse, restResponse)) {
        return;
      }
      var soapData = soapResponse.getData();
      var restData = restResponse.getData();
      compareLists(operationName, soapData, restData, request);
    } catch (Exception ex) {
      log.error("Error comparing SOAP and REST PageableListDto responses for {}.\nSOAP:\n\t{}\nREST:\n\t{}",
          operationName, soapResponse, restResponse, ex);
    }
  }

  private <T extends Serializable, R> void compareLists(String operationName, List<T> soapData, List<T> restData, R request) {
    if (checkData(operationName, soapData, restData)) {
      return;
    }
    int missing = 0;
    var sb = new StringBuilder();
    for (int i = 0; i < soapData.size(); i++) {
      T soapItem = soapData.get(i);
      List<ComparisonDifference> closestDiffs = findClosestDiffs(soapItem, restData);
      if (closestDiffs.isEmpty()) {
        continue;
      }
      missing++;
      String indexedPath = "data[" + i + "]";
      sb.append("\n  - SOAP item not found in REST response (").append(indexedPath)
          .append("): ").append(closestDiffs.size()).append(" field(s) differ from closest REST item");
      appendDiffsTabular(sb, closestDiffs, diff -> diff.getDecomposedPath().isEmpty() ? indexedPath
          : indexedPath + "." + String.join(".", diff.getDecomposedPath()));
    }
    if (missing == 0) {
      log.debug("Shadow REST and SOAP responses match for {} ({} SOAP items all found in REST)", operationName, soapData.size());
    } else {
      sb.insert(0, "Shadow REST and SOAP responses differ for "
          + operationName + ": " + restData.size() + " items REST/"
          + soapData.size() + " items SOAP. Found " + missing + " discrepancies.");
      sb.append("\n  - Request body used: ").append(request);
      log.warn(sb.toString());
    }
  }

  private static void appendDiffsTabular(StringBuilder sb, List<ComparisonDifference> diffs,
      Function<ComparisonDifference, String> pathExtractor) {
    if (diffs.isEmpty()) {
      return;
    }
    // Compute column widths
    int maxPath = 0;
    int maxSoap = 0;
    int maxRest = 0;
    for (ComparisonDifference diff : diffs) {
      String path = pathExtractor.apply(diff);
      if (path.isEmpty()) {
        continue;
      }
      maxPath = Math.max(maxPath, path.length());
      maxSoap = Math.max(maxSoap, nullFormatted(diff.getExpected()).length());
      maxRest = Math.max(maxRest, nullFormatted(diff.getActual()).length());
    }
    // Append rows
    for (ComparisonDifference diff : diffs) {
      String path = pathExtractor.apply(diff);
      if (path.isEmpty()) {
        continue;
      }
      String soapVal = nullFormatted(diff.getExpected());
      String restVal = nullFormatted(diff.getActual());
      sb.append(("\n      %-" + (maxPath + 7) + "s  SOAP | %s | %s | REST").formatted(
          "Field: " + path, center(soapVal, maxSoap), center(restVal, maxRest)));
    }
  }

  private static String center(String text, int width) {
    if (text.length() >= width) {
      return text;
    }
    int totalPad = width - text.length();
    int left = totalPad / 2;
    int right = totalPad - left;
    return " ".repeat(left) + text + " ".repeat(right);
  }

  private static String nullFormatted(Object value) {
    if (value == null) {
      return "<null>";
    }
    if (value instanceof String) {
      return "\"" + value + "\"";
    }
    return String.valueOf(value);
  }

  private <T> List<ComparisonDifference> findClosestDiffs(T soapItem, List<T> restData) {
    List<ComparisonDifference> closest = null;
    for (T restItem : restData) {
      List<ComparisonDifference> diffs = calculator.determineDifferences(restItem, soapItem, COMPARISON_CONFIG);
      if (diffs.isEmpty()) {
        return diffs;
      }
      if (closest == null || diffs.size() < closest.size()) {
        closest = diffs;
      }
    }
    return closest == null ? List.of() : closest;
  }

  private static <T extends Serializable> boolean checkResponses(String operationName, PageableListDto<T> soapResponse,
      PageableListDto<T> restResponse) {
    if (soapResponse == null && restResponse == null) {
      log.debug("Shadow REST and SOAP responses match for {} (both null)", operationName);
      return true;
    }
    if (soapResponse == null || restResponse == null) {
      log.warn("Shadow REST and SOAP responses differ for {}. SOAP: {}. REST: {}", operationName, soapResponse, restResponse);
      return true;
    }
    return false;
  }

  private static <T extends Serializable> boolean checkData(String operationName, List<T> soapData, List<T> restData) {
    if (soapData == null || soapData.isEmpty()) {
      log.debug("Shadow REST and SOAP responses match for {} (SOAP data empty)", operationName);
      return true;
    }
    if (restData == null || restData.isEmpty()) {
      log.warn("Shadow REST and SOAP responses differ for {}: REST data is empty but SOAP has {} elements",
          operationName, soapData.size());
      return true;
    }
    return false;
  }

}
